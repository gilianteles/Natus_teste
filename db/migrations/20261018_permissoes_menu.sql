-- Natus — Configurações: personalização da barra lateral por perfil.
-- Repetível (idempotente) e aditiva: não altera nem apaga dados de negócio. O controle é apenas
-- de EXIBIÇÃO do menu; as permissões de rota continuam em lib/auth.js e nas guardas de tela.
BEGIN;

CREATE TABLE IF NOT EXISTS permissoes_menu (
  id_permissao   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  perfil         text NOT NULL,
  modulo_chave   text NOT NULL,
  visivel        boolean NOT NULL DEFAULT true,
  atualizado_em  timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'America/Manaus'),
  CONSTRAINT unq_perfil_modulo UNIQUE (perfil, modulo_chave)
);
CREATE INDEX IF NOT EXISTS ix_permissoes_menu_perfil ON permissoes_menu (lower(perfil));

-- Semente das combinações perfil x módulo, espelhando a navegação atual (ON CONFLICT preserva
-- escolhas já feitas pelos administradores).
INSERT INTO permissoes_menu (perfil, modulo_chave, visivel)
SELECT p.perfil, m.chave,
       CASE
         WHEN m.chave = 'configuracoes' THEN upper(p.perfil) IN ('ADMINISTRADOR', 'ADMIN')
         WHEN m.chave IN ('dashboardgeral', 'nir', 'kanban', 'bi')
           THEN upper(p.perfil) IN ('NIR', 'SAME', 'NIR/SAME', 'GESTÃO', 'ADMINISTRADOR', 'ADMIN')
         ELSE true
       END
FROM (VALUES ('Administrador'), ('Operador'), ('Visualizador'), ('NIR'), ('SAME'), ('NIR/SAME'), ('Gestão'), ('Setor')) AS p(perfil)
CROSS JOIN (VALUES ('censo'), ('dashboard'), ('acr'), ('chamada'), ('historico'),
                   ('dashboardgeral'), ('nir'), ('kanban'), ('bi'), ('configuracoes')) AS m(chave)
ON CONFLICT (perfil, modulo_chave) DO NOTHING;

COMMIT;
